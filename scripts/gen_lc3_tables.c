/* Our own tool (not liblc3 code): emits crates/lc3/src/tables.rs from liblc3's compiled
 * tables (`just lc3-tables`): includes tables.c itself (and spec.c, sns.c, tns.c for their function-local tables, read through
 * their static functions), so every value is the float the C compiler produced, printed with 9
 * significant digits (exact for f32: Rust parses it back to the same float). Shared tables
 * (one rotation for several (dt, sr)) are emitted once, named by their first use.
 * Function-local tables of the encoder (and ltpf.c's file statics) come through
 * lc3_locals.h: their definitions as written in the C, cut out by the recipe's awk.
 * Build: `just lc3-tables` (links bits.c, bwdet.c, ltpf.c and libm). */
#include "tables.c"
#define quantize spec_quantize
#define unquantize spec_unquantize
#include "spec.c"
#undef quantize
#undef unquantize
#include "sns.c"
#include "tns.c"
#include "lc3_locals.h"
#include <stdio.h>

#define NDT LC3_NUM_DT
#define NSR LC3_NUM_SRATE
#define LEN(a) ((int)(sizeof(a) / sizeof((a)[0])))

static void floats(const float *v, int n)
{
    for (int i = 0; i < n; i++)
        printf("%s%.8e,", i % 6 ? " " : "\n    ", v[i]);
    printf("\n");
}

static void complexes(const struct lc3_complex *v, int n)
{
    for (int i = 0; i < n; i++)
        printf("%sc(%.8e, %.8e),", i % 3 ? " " : "\n    ", v[i].re, v[i].im);
    printf("\n");
}

static void ints(const char *ty, const int *v, int n)
{
    printf("[");
    for (int i = 0; i < n; i++) printf("%s%d", i ? ", " : "", v[i]);
    printf("]%s", ty);
}

static void u16s(const uint16_t *v, int n)
{
    printf("[");
    for (int i = 0; i < n; i++) printf("%s%d", i ? ", " : "", v[i]);
    printf("],\n");
}

static void i16s(const int16_t *v, int n)
{
    for (int i = 0; i < n; i++) printf("%s%d,", i % 12 ? " " : "\n    ", v[i]);
    printf("\n");
}

static void model(const struct lc3_ac_model *m)
{
    printf("    [");
    for (int i = 0; i < 17; i++) printf("%s[%d, %d]", i ? ", " : "", m->s[i].low, m->s[i].range);
    printf("],\n");
}

/* Index of the first slot of `p` holding `x` (the name of a shared table) */
static int first(const void *const *p, int n, const void *x)
{
    for (int i = 0; i < n; i++)
        if (p[i] == x)
            return i;
    return -1;
}

int main(void)
{
    printf("// @generated by scripts/gen_lc3_tables.c from liblc3 1.1.3 (Apache-2.0).\n"
           "// Do not edit: run `just lc3-tables`. Names are the C names in upper case;\n"
           "// [dt][sr] arrays are indexed as the C enums (dt: 2.5, 5, 7.5, 10 ms;\n"
           "// sr: 8, 16, 24, 32, 48 kHz, 48 and 96 kHz high resolution).\n"
           "#![allow(dead_code, clippy::excessive_precision, clippy::approx_constant)]\n\n"
           "use crate::bits::AcModel;\nuse crate::mdct::{Complex, c};\n\n");

    printf("/// Samples per 2.5 ms, per sample rate.\n"
           "pub(crate) const LC3_NS_2M5: [usize; %d] = [", NSR);
    for (int s = 0; s < NSR; s++) printf("%s%d", s ? ", " : "", lc3_ns_2m5[s]);
    printf("];\n/// Samples per 4 ms, per sample rate (the 7.5 ms MDCT overlap).\n"
           "pub(crate) const LC3_NS_4M: [usize; %d] = [", NSR);
    for (int s = 0; s < NSR; s++) printf("%s%d", s ? ", " : "", lc3_ns_4m[s]);
    printf("];\n\n");

    /* FFT radix-3 twiddles: 3 * n3 pairs each */
    int nb3 = LEN(lc3_fft_twiddles_bf3);
    for (int i = 0; i < nb3; i++) {
        const struct lc3_fft_bf3_twiddles *t = lc3_fft_twiddles_bf3[i];
        printf("static FFT_TWIDDLES_BF3_%d: [[Complex; 2]; %d] = [", i, 3 * t->n3);
        for (int j = 0; j < 3 * t->n3; j++)
            printf("\n    [c(%.8e, %.8e), c(%.8e, %.8e)],",
                   t->t[j][0].re, t->t[j][0].im, t->t[j][1].re, t->t[j][1].im);
        printf("\n];\n");
    }
    printf("/// `lc3_fft_twiddles_bf3`: radix-3 stage `i3`, `n3` = len / 3.\n"
           "pub(crate) static LC3_FFT_TWIDDLES_BF3: [&[[Complex; 2]]; %d] = [", nb3);
    for (int i = 0; i < nb3; i++) printf("%s&FFT_TWIDDLES_BF3_%d", i ? ", " : "", i);
    printf("];\n\n");

    /* FFT radix-2 twiddles [i2][i3]: n2 each, shared by pointer */
    int nb2 = LEN(lc3_fft_twiddles_bf2);
    const void *bf2[LEN(lc3_fft_twiddles_bf2) * 3];
    for (int i = 0; i < nb2; i++)
        for (int j = 0; j < 3; j++) {
            const struct lc3_fft_bf2_twiddles *t = lc3_fft_twiddles_bf2[i][j];
            int k = i * 3 + j;
            bf2[k] = t;
            if (!t || first(bf2, k, t) >= 0) continue;
            printf("static FFT_TWIDDLES_BF2_%d_%d: [Complex; %d] = [", i, j, t->n2);
            complexes(t->t, t->n2);
            printf("];\n");
        }
    printf("/// `lc3_fft_twiddles_bf2[i2][i3]`: `n2` = len.\n"
           "pub(crate) static LC3_FFT_TWIDDLES_BF2: [[Option<&[Complex]>; 3]; %d] = [\n", nb2);
    for (int i = 0; i < nb2; i++) {
        printf("    [");
        for (int j = 0; j < 3; j++) {
            int k = first(bf2, nb2 * 3, bf2[i * 3 + j]);
            if (!bf2[i * 3 + j]) printf("%sNone", j ? ", " : "");
            else printf("%sSome(&FFT_TWIDDLES_BF2_%d_%d)", j ? ", " : "", k / 3, k % 3);
        }
        printf("],\n");
    }
    printf("];\n\n");

    /* MDCT rotations [dt][sr]: n4 each, shared by pointer */
    const void *rot[NDT * NSR];
    for (int d = 0; d < NDT; d++)
        for (int s = 0; s < NSR; s++) {
            const struct lc3_mdct_rot_def *r = lc3_mdct_rot[d][s];
            int k = d * NSR + s;
            rot[k] = r;
            if (!r || first(rot, k, r) >= 0) continue;
            printf("static MDCT_ROT_%d: [Complex; %d] = [", 4 * r->n4, r->n4);
            complexes(r->w, r->n4);
            printf("];\n");
        }
    printf("/// `lc3_mdct_rot[dt][sr]`: `n4` = len.\n"
           "pub(crate) static LC3_MDCT_ROT: [[Option<&[Complex]>; %d]; %d] = [\n", NSR, NDT);
    for (int d = 0; d < NDT; d++) {
        printf("    [");
        for (int s = 0; s < NSR; s++) {
            const struct lc3_mdct_rot_def *r = lc3_mdct_rot[d][s];
            if (!r) printf("%sNone", s ? ", " : "");
            else printf("%sSome(&MDCT_ROT_%d)", s ? ", " : "", 4 * r->n4);
        }
        printf("],\n");
    }
    printf("];\n\n");

    /* MDCT windows [dt][sr]: ns + nd each */
    const void *win[NDT * NSR];
    for (int d = 0; d < NDT; d++)
        for (int s = 0; s < NSR; s++) {
            const float *w = lc3_mdct_win[d][s];
            int k = d * NSR + s;
            win[k] = w;
            if (!w || first(win, k, w) >= 0) continue;
            int n = lc3_ns(d, s) + lc3_nd(d, s);
            printf("static MDCT_WIN_%d_%d: [f32; %d] = [", d, s, n);
            floats(w, n);
            printf("];\n");
        }
    printf("/// `lc3_mdct_win[dt][sr]`: ns + nd samples.\n"
           "pub(crate) static LC3_MDCT_WIN: [[Option<&[f32]>; %d]; %d] = [\n", NSR, NDT);
    for (int d = 0; d < NDT; d++) {
        printf("    [");
        for (int s = 0; s < NSR; s++) {
            int k = first(win, NDT * NSR, win[d * NSR + s]);
            if (!win[d * NSR + s]) printf("%sNone", s ? ", " : "");
            else printf("%sSome(&MDCT_WIN_%d_%d)", s ? ", " : "", k / NSR, k % NSR);
        }
        printf("],\n");
    }
    printf("];\n\n");

    printf("/// Encoded coefficients per 2.5 ms, per sample rate.\n"
           "pub(crate) const LC3_NE_2M5: [usize; %d] = ", NSR);
    ints(";\n", lc3_ne_2m5, NSR);
    printf("/// `lc3_num_bands[dt][sr]`.\npub(crate) const LC3_NUM_BANDS: [[usize; %d]; %d] = [\n", NSR, NDT);
    for (int d = 0; d < NDT; d++) { printf("    "); ints(",\n", lc3_num_bands[d], NSR); }
    printf("];\n");
    for (int d = 0; d < NDT; d++)
        for (int s = 0; s < NSR; s++)
            if (lc3_band_lim[d][s]) {
                printf("static BAND_LIM_%d_%d: [usize; %d] = ", d, s, lc3_num_bands[d][s] + 1);
                ints(";\n", lc3_band_lim[d][s], lc3_num_bands[d][s] + 1);
            }
    printf("/// `lc3_band_lim[dt][sr]`: num_bands + 1 limits.\n"
           "pub(crate) static LC3_BAND_LIM: [[Option<&[usize]>; %d]; %d] = [\n", NSR, NDT);
    for (int d = 0; d < NDT; d++) {
        printf("    [");
        for (int s = 0; s < NSR; s++)
            if (lc3_band_lim[d][s]) printf("%sSome(&BAND_LIM_%d_%d)", s ? ", " : "", d, s);
            else printf("%sNone", s ? ", " : "");
        printf("],\n");
    }
    printf("];\n\n");

    const char *cb[] = { "LFCB", "HFCB" };
    const float (*cbv[])[8] = { lc3_sns_lfcb, lc3_sns_hfcb };
    for (int t = 0; t < 2; t++) {
        printf("/// `lc3_sns_%s`.\npub(crate) static LC3_SNS_%s: [[f32; 8]; 32] = [\n", t ? "hfcb" : "lfcb", cb[t]);
        for (int i = 0; i < 32; i++) { printf("    ["); floats(cbv[t][i], 8); printf("    ],\n"); }
        printf("];\n");
    }
    for (int i = 0; i < 4; i++) {
        printf("static SNS_VQ_GAINS_%d: [f32; %d] = [", i, lc3_sns_vq_gains[i].count);
        floats(lc3_sns_vq_gains[i].v, lc3_sns_vq_gains[i].count);
        printf("];\n");
    }
    printf("/// `lc3_sns_vq_gains[shape]`.\npub(crate) static LC3_SNS_VQ_GAINS: [&[f32]; 4] = "
           "[&SNS_VQ_GAINS_0, &SNS_VQ_GAINS_1, &SNS_VQ_GAINS_2, &SNS_VQ_GAINS_3];\n");
    printf("/// `lc3_sns_mpvq_offsets`.\npub(crate) static LC3_SNS_MPVQ_OFFSETS: [[i32; 11]; %d] = [\n",
           LEN(lc3_sns_mpvq_offsets));
    for (int i = 0; i < LEN(lc3_sns_mpvq_offsets); i++) {
        printf("    "); ints(",\n", (const int *)lc3_sns_mpvq_offsets[i], 11);
    }
    printf("];\n");
    printf("/// `dct16_m` (`sns.c`).\npub(crate) static DCT16_M: [[f32; 16]; 16] = [\n");
    for (int i = 0; i < 16; i++) { printf("    ["); floats(dct16_m[i], 16); printf("    ],\n"); }
    printf("];\n\n");

    printf("/// `lc3_tns_order_models`.\npub(crate) static LC3_TNS_ORDER_MODELS: [AcModel; %d] = [\n",
           LEN(lc3_tns_order_models));
    for (int i = 0; i < LEN(lc3_tns_order_models); i++) model(&lc3_tns_order_models[i]);
    printf("];\n/// `lc3_tns_coeffs_models`.\npub(crate) static LC3_TNS_COEFFS_MODELS: [AcModel; %d] = [\n",
           LEN(lc3_tns_coeffs_models));
    for (int i = 0; i < LEN(lc3_tns_coeffs_models); i++) model(&lc3_tns_coeffs_models[i]);
    printf("];\n");
    {
        int q[8] = { 0, 1, 2, 3, 4, 5, 6, 7 }, q8[1] = { 8 };
        float r[16];
        unquantize_rc(q, 8, r);
        unquantize_rc(q8, 1, r + 8);
        printf("/// `q_inv` (`tns.c` `unquantize_rc`).\npub(crate) static TNS_Q_INV: [f32; 9] = [");
        floats(r, 9);
        printf("];\n");
    }
    {
        float g[28];
        for (int i = 0; i < 28; i++) g[i] = unquantize_gain(i);
        printf("/// `iq_table` (`spec.c` `unquantize_gain`).\npub(crate) static SPEC_IQ_TABLE: [f32; 28] = [");
        floats(g, 28);
        printf("];\n\n");
    }

    for (int s = 0; s < LC3_SRATE_48K_HR; s++) {
        int w = LC3_MAX(4, lc3_ns_4m[s] >> 4);
        printf("/// `lc3_ltpf_cnum[%d]`, `lc3_ltpf_cden[%d]` (the `w` = %d taps used).\n", s, s, w);
        printf("static LTPF_CNUM_%d: [[f32; %d]; 4] = [\n", s, w);
        for (int i = 0; i < 4; i++) { printf("    ["); floats(lc3_ltpf_cnum[s][i], w); printf("    ],\n"); }
        printf("];\nstatic LTPF_CDEN_%d: [[f32; %d]; 4] = [\n", s, w);
        for (int i = 0; i < 4; i++) { printf("    ["); floats(lc3_ltpf_cden[s][i], w); printf("    ],\n"); }
        printf("];\n");
    }
    for (int t = 0; t < 2; t++) {
        const char *n = t ? "CDEN" : "CNUM";
        printf("/// `lc3_ltpf_%s[sr][i]` (8 to 48 kHz).\n"
               "pub(crate) fn lc3_ltpf_%s(sr: usize, i: usize) -> &'static [f32] {\n    match sr {\n",
               t ? "cden" : "cnum", t ? "cden" : "cnum");
        for (int s = 0; s < LC3_SRATE_48K_HR; s++) printf("        %d => &LTPF_%s_%d[i],\n", s, n, s);
        printf("        _ => unreachable!(\"no LTPF at high resolution\"),\n    }\n}\n");
    }
    printf("\n");

    printf("/// `lc3_spectrum_lookup[high_rate][h][state]`.\n"
           "pub(crate) static LC3_SPECTRUM_LOOKUP: [[[[u8; 4]; 256]; 2]; 2] = [\n");
    for (int a = 0; a < 2; a++) {
        printf("  [\n");
        for (int b = 0; b < 2; b++) {
            printf("    [\n");
            for (int i = 0; i < 256; i++)
                printf("%s[%d, %d, %d, %d],%s", i % 6 ? " " : "      ",
                       lc3_spectrum_lookup[a][b][i][0], lc3_spectrum_lookup[a][b][i][1],
                       lc3_spectrum_lookup[a][b][i][2], lc3_spectrum_lookup[a][b][i][3],
                       i % 6 == 5 || i == 255 ? "\n" : "");
            printf("    ],\n");
        }
        printf("  ],\n");
    }
    printf("];\n/// `lc3_spectrum_bits`: bits (Q11) per symbol of each model.\n"
           "pub(crate) static LC3_SPECTRUM_BITS: [[u16; 17]; %d] = [\n", LEN(lc3_spectrum_bits));
    for (int i = 0; i < LEN(lc3_spectrum_bits); i++) { printf("    "); u16s(lc3_spectrum_bits[i], 17); }
    printf("];\n/// `lc3_spectrum_models`.\npub(crate) static LC3_SPECTRUM_MODELS: [AcModel; %d] = [\n",
           LEN(lc3_spectrum_models));
    for (int i = 0; i < LEN(lc3_spectrum_models); i++) model(&lc3_spectrum_models[i]);
    printf("];\n\n");

    /* Encoder */
    printf("/// `lc3_tns_order_bits` (Q11).\npub(crate) static LC3_TNS_ORDER_BITS: [[u16; 8]; 2] = [\n");
    for (int i = 0; i < 2; i++) { printf("    "); u16s(lc3_tns_order_bits[i], 8); }
    printf("];\n/// `lc3_tns_coeffs_bits` (Q11).\npub(crate) static LC3_TNS_COEFFS_BITS: [[u16; 17]; 8] = [\n");
    for (int i = 0; i < 8; i++) { printf("    "); u16s(lc3_tns_coeffs_bits[i], 17); }
    printf("];\n/// `lag_window` (`tns.c` `compute_lpc_coeffs`).\npub(crate) static TNS_LAG_WINDOW: [f32; 9] = [");
    floats(lag_window, 9);
    printf("];\n");
    {
        const float *ge[] = { ge_14, ge_18, ge_22, ge_26, ge_30 };
        printf("/// `ge_table[sr]` (`sns.c` `compute_scale_factors`): pre-emphasis gains, 8 to 48 kHz.\n"
               "pub(crate) static SNS_GE: [[f32; 64]; 5] = [\n");
        for (int i = 0; i < 5; i++) { printf("    ["); floats(ge[i], 64); printf("    ],\n"); }
        printf("];\n");
    }
    printf("/// `h4` (`ltpf.c` `interpolate_corr`).\npub(crate) static LTPF_H4_CORR: [[f32; 8]; 4] = [\n");
    for (int i = 0; i < 4; i++) { printf("    ["); floats(h4[i], 8); printf("    ],\n"); }
    printf("];\n");
    {
        const char *n[] = { "8K", "16K", "24K", "32K", "48K" }, *l[] = { "8", "16", "24", "32", "48" };
        const int16_t *h[] = { h_8k_12k8_q15, h_16k_12k8_q15, h_24k_12k8_q15, h_32k_12k8_q15, h_48k_12k8_q15 };
        int len[] = { LEN(h_8k_12k8_q15), LEN(h_16k_12k8_q15), LEN(h_24k_12k8_q15),
                      LEN(h_32k_12k8_q15), LEN(h_48k_12k8_q15) };
        for (int i = 0; i < 5; i++) {
            printf("/// `h_%sk_12k8_q15` (`ltpf.c`): resampling to 12.8 kHz, by phase.\n"
                   "pub(crate) static LTPF_H_%s_12K8: [i16; %d] = [", l[i], n[i], len[i]);
            i16s(h[i], len[i]);
            printf("];\n");
        }
    }
    return 0;
}
